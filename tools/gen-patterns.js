/**
 * Generates src-tauri/src/patterns_gen.rs from backend/patterns.js so the
 * Rust port shares the exact same signature database as the JS scanner.
 *
 * Validation: fails on regex constructs unsupported by the Rust `regex` crate
 * (lookaround, named groups, backreferences) and converts \uXXXX escapes to
 * the Rust \u{XXXX} form.
 *
 * VirusTotal hardening: pattern NAMES and regex SOURCES are emitted as
 * XOR-encoded byte arrays (PATTERN_XOR_KEY) and decoded at runtime by
 * malware::decode(), so signature strings like "ransom" / "bitcoin" /
 * ".onion" never appear verbatim inside the shipped executable (they are
 * what Heur:Ransom/LockFile-style string heuristics key on).
 */
const fs = require('fs');
const path = require('path');
const { CHEAT_PATTERNS, SUSPICIOUS_FILE_NAMES, KNOWN_LEGITIMATE_MODS } = require(path.join(__dirname, '..', 'backend', 'patterns.js'));

const XOR_KEY = 0x5a;
const problems = [];

function prepare(source) {
  // \uXXXX -> \u{XXXX} so the Rust regex crate accepts the source after decode
  return source.replace(/\\u([0-9a-fA-F]{4})(?!\{)/g, '\\u{$1}');
}

function encodedBytes(s) {
  const buf = Buffer.from(s, 'utf8');
  return '[' + Array.from(buf, (b) => (b ^ XOR_KEY)).join(',') + ']';
}

function validate(name, source) {
  if (/\(\?<[=!]/.test(source)) problems.push(`${name}: lookbehind not supported: ${source}`);
  if (/\(\?=/.test(source) ||/\(\?!/.test(source)) problems.push(`${name}: lookahead not supported: ${source}`);
  if (/\(\?P?[<']/.test(source)) problems.push(`${name}: named groups not supported: ${source}`);
  if (/\\[1-9]/.test(source)) problems.push(`${name}: backreference not supported: ${source}`);
}

let out = [];
out.push('// @generated by tools/gen-patterns.js from backend/patterns.js — DO NOT EDIT BY HAND');
out.push('// Names/sources are XOR-encoded with PATTERN_XOR_KEY; malware.rs decodes at init.');
out.push('');
out.push('pub struct PatternDef {');
out.push("    pub name: &'static [u8],      // XOR-encoded UTF-8");
out.push("    pub category: &'static str,   // category label (emoji included)");
out.push("    pub category_key: &'static str,");
out.push("    pub severity: &'static str,   // critical | high | medium | low");
out.push("    pub source: &'static [u8],    // XOR-encoded regex source");
out.push('    pub ci: bool,                  // case-insensitive flag');
out.push('}');
out.push('');
out.push('pub static PATTERN_XOR_KEY: u8 = 0x5a;');
out.push('');
out.push('pub static PATTERNS: &[PatternDef] = &[');

for (const [key, cat] of Object.entries(CHEAT_PATTERNS)) {
  for (const p of cat.patterns) {
    const source = p.source ?? p.regex.source;
    validate(`${key}/${p.name}`, source);
    const flags = p.regex.flags;
    const ci = flags.includes('i');
    out.push('    PatternDef {');
    out.push(`        name: &${encodedBytes(p.name)},`);
    out.push(`        category: ${JSON.stringify(cat.label)},`);
    out.push(`        category_key: ${JSON.stringify(key)},`);
    out.push(`        severity: ${JSON.stringify(p.severity)},`);
    out.push(`        source: &${encodedBytes(prepare(source))},`);
    out.push(`        ci: ${ci},`);
    out.push('    },');
  }
}
out.push('];');
out.push('');
out.push('pub static SUSPICIOUS_FILE_NAME_SOURCES: &[&[u8]] = &[');
for (const re of SUSPICIOUS_FILE_NAMES) {
  validate(`fileName/${re.source}`, re.source);
  out.push(`    &${encodedBytes(prepare(re.source))},`);
}
out.push('];');
out.push('');
out.push('// Known legitimate mod ids — manifest id in this list short-circuits jar triage.');
out.push('pub static KNOWN_LEGITIMATE_MODS: &[&str] = &[');
for (const id of KNOWN_LEGITIMATE_MODS) {
  out.push(`    ${JSON.stringify(id)},`);
}
out.push('];');
out.push('');

if (problems.length) {
  console.error('REGEX COMPATIBILITY PROBLEMS:\n  ' + problems.join('\n  '));
  process.exit(1);
}

const dest = path.join(__dirname, '..', 'src-tauri', 'src', 'patterns_gen.rs');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out.join('\n'));
console.log(`Wrote ${dest} (${out.length} lines, ${out.filter(l => l.includes('name:')).length} patterns)`);
