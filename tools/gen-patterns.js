/**
 * Generates src-tauri/src/patterns_gen.rs from backend/patterns.js so the
 * Rust port shares the exact same signature database as the JS scanner.
 *
 * Validation: fails on regex constructs unsupported by the Rust `regex` crate
 * (lookaround, named groups, backreferences) and converts \uXXXX escapes to
 * the Rust \u{XXXX} form.
 */
const fs = require('fs');
const path = require('path');
const { CHEAT_PATTERNS, SUSPICIOUS_FILE_NAMES } = require(path.join(__dirname, '..', 'backend', 'patterns.js'));

const problems = [];

function rustEscape(s) {
  return s
    .replace(/\\u([0-9a-fA-F]{4})(?!\{)/g, '\\u{$1}')   // \uXXXX -> \u{XXXX}
    .replace(/\\/g, '\\\\')                            // escape backslashes for Rust string literals
    .replace(/"/g, '\\"')
    .replace(/\r?\n/g, '\\n');
}

function validate(name, source) {
  if (/\(\?<[=!]/.test(source)) problems.push(`${name}: lookbehind not supported: ${source}`);
  if (/\(\?=/.test(source) || /\(\?!/.test(source)) problems.push(`${name}: lookahead not supported: ${source}`);
  if (/\(\?P?[<']/.test(source)) problems.push(`${name}: named groups not supported: ${source}`);
  if (/\\[1-9]/.test(source)) problems.push(`${name}: backreference not supported: ${source}`);
}

let out = [];
out.push('// @generated by tools/gen-patterns.js from backend/patterns.js — DO NOT EDIT BY HAND');
out.push('');
out.push('pub struct PatternDef {');
out.push('    pub name: &\'static str,');
out.push('    pub category: &\'static str,   // category label (emoji included)');
out.push('    pub category_key: &\'static str,');
out.push('    pub severity: &\'static str,   // critical | high | medium | low');
out.push('    pub source: &\'static str,     // regex source');
out.push('    pub ci: bool,                  // case-insensitive flag');
out.push('}');
out.push('');
out.push('pub static PATTERNS: &[PatternDef] = &[');

for (const [key, cat] of Object.entries(CHEAT_PATTERNS)) {
  for (const p of cat.patterns) {
    validate(`${key}/${p.name}`, p.source ?? p.regex.source);
    const flags = p.regex.flags;
    const ci = flags.includes('i');
    out.push('    PatternDef {');
    out.push(`        name: ${JSON.stringify(p.name)},`);
    out.push(`        category: ${JSON.stringify(cat.label)},`);
    out.push(`        category_key: ${JSON.stringify(key)},`);
    out.push(`        severity: ${JSON.stringify(p.severity)},`);
    out.push(`        source: "${rustEscape(p.regex.source)}",`);
    out.push(`        ci: ${ci},`);
    out.push('    },');
  }
}
out.push('];');
out.push('');
out.push('pub static SUSPICIOUS_FILE_NAME_SOURCES: &[&str] = &[');
for (const re of SUSPICIOUS_FILE_NAMES) {
  validate(`fileName/${re.source}`, re.source);
  out.push(`    "${rustEscape(re.source)}",`);
}
out.push('];');
out.push('');

if (problems.length) {
  console.error('REGEX COMPATIBILITY PROBLEMS:\n  ' + problems.join('\n  '));
  process.exit(1);
}

const dest = path.join(__dirname, '..', 'src-tauri', 'src', 'patterns_gen.rs');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out.join('\n'));
console.log(`Wrote ${dest} (${out.length} lines, ${out.filter(l => l.includes('name:')).length} patterns)`);
